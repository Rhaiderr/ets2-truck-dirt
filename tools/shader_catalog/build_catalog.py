"""Builds the shader catalog: DXBC checksum -> effect name and pass.

Reads the .rfx effects and the SM5X shaders extracted from effect.scs
(probe/effect, see README-dev.md) and writes:
  - catalog/shaders_sm5x.csv            checksum,kind,file,outputs,uses
  - src/generated/shader_catalog.inc    pixel shaders only, for the DLL

The game runs the D3D11 "SM5X rendering path" [verified: game.log.txt], so
only the sm5x technique of each effect matters. A shader file (.fso/.vso)
starts with an "SHDO" header; the DXBC blob the game hands to
CreatePixelShader starts at "DXBC", and bytes 4..20 of it are the checksum.

Usage: python -I build_catalog.py <probe/effect dir> <project root>
"""
import os
import re
import struct
import sys
from collections import defaultdict

PASS_RE = re.compile(r'pass\s*\{(.*?)\}', re.S)
TECH_RE = re.compile(r'technique\s*\{\s*predicate\s*\{\s*path:\s*(\w+)\s*\}(.*?)(?=technique\s*\{|\Z)', re.S)


def field(block, name):
    m = re.search(name + r':\s*"?([^"\s]+)"?', block)
    return m.group(1) if m else ''


def dxbc_info(path):
    data = open(path, 'rb').read()
    base = data.find(b'DXBC')
    if base < 0:
        return None
    d = data[base:]
    checksum = d[4:20].hex()
    outputs = 0
    try:
        n = struct.unpack_from('<I', d, 28)[0]
        for off in struct.unpack_from('<%dI' % n, d, 32):
            if d[off:off + 4] in (b'OSGN', b'OSG5', b'OSG1'):
                outputs = struct.unpack_from('<I', d, off + 8)[0]
    except struct.error:
        pass
    return checksum, outputs


def main():
    effect_dir, root = sys.argv[1], sys.argv[2]
    uses = defaultdict(set)  # shader game path -> {"effect/semantics/state"}
    for dirpath, _, files in os.walk(effect_dir):
        for name in files:
            if not name.endswith('.rfx'):
                continue
            text = open(os.path.join(dirpath, name), encoding='latin-1').read()
            effect = name[:-4]
            for tech in TECH_RE.finditer(text):
                if tech.group(1) != 'sm5x':
                    continue
                for p in PASS_RE.finditer(tech.group(2)):
                    block = p.group(1)
                    sem = field(block, 'semantics')
                    state = os.path.basename(field(block, 'state_setup')).replace('.rs', '')
                    for key in ('vertex_setup', 'fragment_setup'):
                        shader = field(block, key)
                        if shader:
                            uses[shader].add('%s/%s/%s' % (effect, sem, state))

    rows = []
    for dirpath, _, files in os.walk(effect_dir):
        for name in files:
            if not (name.endswith('.sm5x.fso') or name.endswith('.sm5x.vso')):
                continue
            full = os.path.join(dirpath, name)
            info = dxbc_info(full)
            if not info:
                continue
            game_path = '/' + os.path.relpath(full, effect_dir).replace(os.sep, '/')
            kind = 'ps' if name.endswith('.fso') else 'vs'
            rows.append((info[0], kind, game_path, info[1], sorted(uses.get(game_path, ()))))
    rows.sort()

    os.makedirs(os.path.join(root, 'catalog'), exist_ok=True)
    with open(os.path.join(root, 'catalog', 'shaders_sm5x.csv'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('checksum,kind,file,outputs,uses\n')
        for c, kind, path, outs, u in rows:
            f.write('%s,%s,%s,%d,%s\n' % (c, kind, path, outs, '|'.join(u)))

    os.makedirs(os.path.join(root, 'src', 'generated'), exist_ok=True)
    seen = set()
    with open(os.path.join(root, 'src', 'generated', 'shader_catalog.inc'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/shader_catalog/build_catalog.py. Do not edit.\n')
        f.write('// {DXBC checksum, first use "effect/semantics/state"} for SM5X pixel shaders.\n')
        for c, kind, path, outs, u in rows:
            if kind != 'ps' or c in seen:
                continue
            seen.add(c)
            label = (u[0] if u else path.rsplit('/', 1)[-1]) + ('' if len(u) <= 1 else ' (+%d)' % (len(u) - 1))
            f.write('{"%s", "%s"},\n' % (c, label.replace('"', '')))
    ps = sum(1 for r in rows if r[1] == 'ps')
    print('shaders: %d (%d pixel, %d unique pixel checksums), effects using them: %d'
          % (len(rows), ps, len(seen), len(uses)))
    glass = [r for r in rows if r[1] == 'ps' and any(x.startswith('def.glassdrops') for x in r[4])]
    print('glassdrops pixel shaders: %d' % len(glass))
    for r in glass:
        print('  ', r[0], r[3], '|'.join(r[4])[:120])


if __name__ == '__main__':
    main()
