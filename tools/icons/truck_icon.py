"""D11i: the wash visit's truck icon, from an SVG path to polygons for src/truck_icon.h.

The overlay draws in axis-aligned quads (no SVG at run time): the path is flattened here into closed polygons in the
SVG's units (0..256), and overlay.cpp fills them (non-zero winding) on its small icon canvas.

Usage: python tools/icons/truck_icon.py third_party/phosphor/truck-trailer-light.svg src/truck_icon.h
"""
import math
import re
import sys

TOKEN = re.compile(r'[MmLlHhVvCcSsQqTtAaZz]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?')
STEPS = 10  # segments per curve or arc


def tokens(d):
    return TOKEN.findall(d)


def arc(p0, rx, ry, phi, large, sweep, p1):
    """SVG elliptical arc (endpoint form) as points after p0 (SVG spec F.6.5)."""
    if rx == 0 or ry == 0:
        return [p1]
    cp, sp = math.cos(math.radians(phi)), math.sin(math.radians(phi))
    dx, dy = (p0[0] - p1[0]) / 2, (p0[1] - p1[1]) / 2
    x1, y1 = cp * dx + sp * dy, -sp * dx + cp * dy
    rx, ry = abs(rx), abs(ry)
    lam = x1 * x1 / (rx * rx) + y1 * y1 / (ry * ry)
    if lam > 1:
        rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num = rx * rx * ry * ry - rx * rx * y1 * y1 - ry * ry * x1 * x1
    den = rx * rx * y1 * y1 + ry * ry * x1 * x1
    k = math.sqrt(max(0.0, num / den)) * (-1 if large == sweep else 1)
    cx1, cy1 = k * rx * y1 / ry, -k * ry * x1 / rx
    cx = cp * cx1 - sp * cy1 + (p0[0] + p1[0]) / 2
    cy = sp * cx1 + cp * cy1 + (p0[1] + p1[1]) / 2

    def ang(ux, uy, vx, vy):
        a = math.atan2(ux * vy - uy * vx, ux * vx + uy * vy)
        return a

    t1 = ang(1, 0, (x1 - cx1) / rx, (y1 - cy1) / ry)
    dt = ang((x1 - cx1) / rx, (y1 - cy1) / ry, (-x1 - cx1) / rx, (-y1 - cy1) / ry)
    if not sweep and dt > 0:
        dt -= 2 * math.pi
    elif sweep and dt < 0:
        dt += 2 * math.pi
    n = max(2, int(math.ceil(abs(dt) / (math.pi / 2) * STEPS / 2)))
    out = []
    for i in range(1, n + 1):
        t = t1 + dt * i / n
        x, y = rx * math.cos(t), ry * math.sin(t)
        out.append((cp * x - sp * y + cx, sp * x + cp * y + cy))
    out[-1] = p1
    return out


def flatten(d):
    t = tokens(d)
    i = 0
    polys, cur = [], []
    x = y = sx = sy = 0.0
    cmd = None

    def num():
        nonlocal i
        v = float(t[i])
        i += 1
        return v

    while i < len(t):
        if re.match(r'[A-Za-z]', t[i]):
            cmd = t[i]
            i += 1
            if cmd in 'Zz':
                if cur:
                    polys.append(cur)
                cur = []
                x, y = sx, sy
                continue
        rel = cmd.islower()
        c = cmd.upper()
        if c == 'M':
            nx, ny = num(), num()
            if rel:
                nx, ny = nx + x, ny + y
            if cur:
                polys.append(cur)
            cur = [(nx, ny)]
            x, y, sx, sy = nx, ny, nx, ny
            cmd = 'l' if rel else 'L'
        elif c == 'L':
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            cur.append((x, y))
        elif c == 'H':
            nx = num()
            x = x + nx if rel else nx
            cur.append((x, y))
        elif c == 'V':
            ny = num()
            y = y + ny if rel else ny
            cur.append((x, y))
        elif c == 'C':
            p = [num() for _ in range(6)]
            if rel:
                p = [p[k] + (x if k % 2 == 0 else y) for k in range(6)]
            for s in range(1, STEPS + 1):
                u = s / STEPS
                a, b, cc, dd = (1 - u) ** 3, 3 * u * (1 - u) ** 2, 3 * u * u * (1 - u), u ** 3
                cur.append((a * x + b * p[0] + cc * p[2] + dd * p[4], a * y + b * p[1] + cc * p[3] + dd * p[5]))
            x, y = p[4], p[5]
        elif c == 'A':
            rx, ry, phi, large, sweep, nx, ny = num(), num(), num(), num(), num(), num(), num()
            if rel:
                nx, ny = nx + x, ny + y
            cur.extend(arc((x, y), rx, ry, phi, int(large), int(sweep), (nx, ny)))
            x, y = nx, ny
        else:
            raise SystemExit('path command not handled: ' + cmd)
    if cur:
        polys.append(cur)
    return polys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    svg = open(src, encoding='utf-8').read()
    d = re.search(r'<path[^>]*\sd="([^"]+)"', svg).group(1)
    polys = flatten(d)
    xs = [p[0] for poly in polys for p in poly]
    ys = [p[1] for poly in polys for p in poly]
    lines = ['// Generated by tools/icons/truck_icon.py from ' + src.replace('\\', '/') + ' (Phosphor Icons, MIT:',
             '// THIRD_PARTY_LICENSES.txt); not edited by hand. D11i: the wash visit\'s truck, closed polygons in the',
             '// SVG\'s units (filled with the non-zero rule), x right, y down.',
             '#pragma once', '', 'namespace truck_icon {', '',
             'constexpr float kMinX = %.2ff, kMinY = %.2ff, kMaxX = %.2ff, kMaxY = %.2ff;' % (min(xs), min(ys), max(xs), max(ys)),
             'constexpr int kPolys = %d;' % len(polys)]
    starts, pts = [], []
    for poly in polys:
        starts.append(len(pts) // 2)
        for p in poly:
            pts += [p[0], p[1]]
    starts.append(len(pts) // 2)
    lines.append('// Polygon k is points kStart[k] .. kStart[k + 1] - 1.')
    lines.append('constexpr int kStart[] = {' + ', '.join(str(s) for s in starts) + '};')
    lines.append('constexpr float kPoints[] = {')
    for k in range(0, len(pts), 12):
        lines.append('    ' + ', '.join('%.2ff' % v for v in pts[k:k + 12]) + ',')
    lines += ['};', '', '}  // namespace truck_icon', '']
    open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('%d polygons, %d points, x %.1f..%.1f, y %.1f..%.1f' % (len(polys), len(pts) // 2, min(xs), max(xs), min(ys), max(ys)))


main()
